def load_demo_data():
    from app.database import check_health
    from app.services.document import import_document

    health = check_health()
    if health["status"] != "ok":
        print("数据库不可用，无法加载演示数据。")
        print(f"健康检查结果: {health}")
        return False

    print(f"开始加载 {len(DEMO_NOTES)} 篇演示笔记...")
    failures = 0
    for i, note in enumerate(DEMO_NOTES, 1):
        try:
            doc = import_document(**note)
            print(f"  [{i}/{len(DEMO_NOTES)}] {note['title']} -> 文档ID={doc['id']}, 分块={doc['chunk_count']}")
        except Exception as e:
            failures += 1
            print(f"  [{i}/{len(DEMO_NOTES)}] 失败: {e}")

    print(f"\n演示数据加载完成。成功 {len(DEMO_NOTES) - failures}/{len(DEMO_NOTES)} 篇。")
    print("注意：所有演示笔记均明确标注为【演示笔记】，不代表真实研究结论。")
    return failures == 0


if __name__ == "__main__":
    success = load_demo_data()
    sys.exit(0 if success else 1)
